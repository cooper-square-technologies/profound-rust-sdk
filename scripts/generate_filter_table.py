#!/usr/bin/env python3

from __future__ import annotations

import json
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

REGISTRY_URL = "https://registry.scalar.com/@profound/apis/external-api/latest?format=json"
OUTPUT = Path(__file__).parents[1] / "src" / "filter" / "table.rs"

OP_VARIANTS = {
    "is": "Is",
    "not_is": "NotIs",
    "in": "In",
    "not_in": "NotIn",
    "contains": "Contains",
    "not_contains": "NotContains",
    "matches": "Matches",
    "contains_case_insensitive": "ContainsCaseInsensitive",
    "not_contains_case_insensitive": "NotContainsCaseInsensitive",
    "exists": "Exists",
}


def load_spec(source: str) -> dict[str, Any]:
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source) as response:
            return json.load(response)
    with Path(source).open(encoding="utf-8") as file:
        return json.load(file)


def rust_variant(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def generate(spec: dict[str, Any]) -> str:
    grammar = spec.get("x-profound-filter-grammar")
    if not grammar:
        raise ValueError("spec has no x-profound-filter-grammar extension")

    fields = grammar["fields"]
    lines = [
        f"pub const MAX_DEPTH: usize = {grammar['max_depth']};",
        "",
        "#[derive(Copy, Clone, Debug, PartialEq, Eq)]",
        "pub enum Layer {",
        "    Prompt,",
        "    Entity,",
        "}",
        "",
        "#[derive(Copy, Clone, Debug, PartialEq, Eq)]",
        "pub enum Op {",
    ]
    lines.extend(f"    {variant}," for variant in OP_VARIANTS.values())
    lines.extend(
        [
            "}",
            "",
            "impl Op {",
            "    pub fn as_str(self) -> &'static str {",
            "        match self {",
        ]
    )
    lines.extend(f'            Self::{variant} => "{op}",' for op, variant in OP_VARIANTS.items())
    lines.extend(
        [
            "        }",
            "    }",
            "}",
            "",
            "#[derive(Copy, Clone, Debug, PartialEq, Eq)]",
            "pub enum Field {",
        ]
    )
    lines.extend(f"    {rust_variant(name)}," for name in fields)
    lines.extend(
        [
            "}",
            "",
            "pub const ALL_FIELDS: &[Field] = &[",
        ]
    )
    lines.extend(f"    Field::{rust_variant(name)}," for name in fields)
    lines.extend(
        [
            "];",
            "",
            "impl Field {",
            "    pub fn name(self) -> &'static str {",
            "        match self {",
        ]
    )
    lines.extend(f'            Self::{rust_variant(name)} => "{name}",' for name in fields)
    lines.extend(
        [
            "        }",
            "    }",
            "",
            "    pub fn layer(self) -> Layer {",
            "        match self {",
        ]
    )
    lines.extend(
        f"            Self::{rust_variant(name)} => Layer::{field['layer'].capitalize()},"
        for name, field in fields.items()
    )
    lines.extend(
        [
            "        }",
            "    }",
            "",
            "    pub fn ops(self) -> &'static [Op] {",
            "        match self {",
        ]
    )
    for name, field in fields.items():
        ops = ", ".join(f"Op::{OP_VARIANTS[op]}" for op in field["ops"])
        lines.append(f"            Self::{rust_variant(name)} => &[{ops}],")
    lines.extend(["        }", "    }", "}"])
    return "\n".join(lines) + "\n"


def main() -> int:
    source = sys.argv[1] if len(sys.argv) > 1 else REGISTRY_URL
    try:
        content = generate(load_spec(source))
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(
            "// Generated by scripts/generate_filter_table.py from the x-profound-filter-grammar extension "
            "of the Profound OpenAPI spec. Do not edit by hand.\n\n"
            + content,
            encoding="utf-8",
        )
        subprocess.run(["rustfmt", "--edition", "2024", str(OUTPUT)], check=True)
    except (OSError, ValueError, json.JSONDecodeError, urllib.error.URLError) as error:
        print(f"failed to generate filter table: {error}", file=sys.stderr)
        return 1
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
